/**
 * DELTA Resilience Core Application Connector
 * Two-way integration: fetches baseline exposure & divisions, and pushes
 * validated post-disaster loss assessments as "Draft" records into DELTA.
 */

const http = require("http");
const https = require("https");
const { CONFIG } = require("./config");

/**
 * Execute a JSON-RPC 2.0 tool call against DELTA's MCP server endpoint
 * @param {string} toolName - e.g. "disaster-record_add", "division_list"
 * @param {object} toolArgs - Tool arguments object
 * @returns {Promise<object>} Result returned by DELTA
 */
function callDeltaMcp(toolName, toolArgs = {}) {
	return new Promise((resolve, reject) => {
		if (!CONFIG.DELTA_MCP_API_KEY) {
			return reject(
				new Error(
					"DELTA_MCP_API_KEY is not configured. Set DELTA_MCP_API_KEY in your environment or .env file.",
				),
			);
		}

		const parsedUrl = new URL(CONFIG.DELTA_API_URL);
		const client = parsedUrl.protocol === "https:" ? https : http;

		const payload = JSON.stringify({
			jsonrpc: "2.0",
			id: Date.now(),
			method: "tools/call",
			params: {
				name: toolName,
				arguments: toolArgs,
			},
		});

		const req = client.request(
			CONFIG.DELTA_API_URL,
			{
				method: "POST",
				headers: {
					"Content-Type": "application/json",
					"Content-Length": Buffer.byteLength(payload),
					"X-Auth": CONFIG.DELTA_MCP_API_KEY,
					"User-Agent": CONFIG.USER_AGENT,
				},
				timeout: CONFIG.REQUEST_TIMEOUT_MS,
			},
			(res) => {
				let data = "";
				res.on("data", (chunk) => (data += chunk));
				res.on("end", () => {
					try {
						const json = JSON.parse(data);
						if (json.error) {
							return reject(
								new Error(`DELTA MCP error: ${json.error.message || JSON.stringify(json.error)}`),
							);
						}
						resolve(json.result);
					} catch (e) {
						reject(new Error(`Failed to parse DELTA response: ${e.message}`));
					}
				});
			},
		);

		req.on("error", (err) => {
			reject(new Error(`Failed to connect to DELTA MCP endpoint: ${err.message}`));
		});

		req.on("timeout", () => {
			req.destroy();
			reject(new Error(`DELTA request timed out after ${CONFIG.REQUEST_TIMEOUT_MS}ms`));
		});

		req.write(payload);
		req.end();
	});
}

/**
 * Format and push a post-disaster assessment as a "Draft" record into DELTA
 * @param {object} params - Assessment parameters (from vulnerability report or emergency brief)
 * @param {object} options - Optional overrides (mock: boolean)
 * @returns {Promise<object>}
 */
async function pushDraftDisasterRecord(params = {}, options = {}) {
	const hazardAssessment = params.hazardAssessment || {};
	const sendai = params.sendaiFrameworkMetrics || {};
	const targetB = sendai.targetB_AffectedPeople || {};
	const targetC = sendai.targetC_DirectEconomicLoss || {};
	const targetD = sendai.targetD_CriticalInfrastructure || {};

	const draftRecord = {
		name: params.name || `${hazardAssessment.hazardType || "Disaster"} Incident Assessment`,
		hazardType: hazardAssessment.hazardType || "General Natural Hazard",
		hazardIntensity: hazardAssessment.hazardIntensity || null,
		intensityUnit: hazardAssessment.intensityUnit || null,
		startDate: params.startDate || new Date().toISOString().split("T")[0],
		status: "draft",
		source: "drr-agent-plugin",
		notes:
			params.notes ||
			`Automated preliminary assessment generated by drr-agent-plugin on ${new Date().toISOString()}. Requires human review.`,
		sendaiMetrics: {
			totalExposedPopulation: targetB.totalExposedPopulation || 0,
			estimatedDisplaced: targetB.estimatedDisplacedPopulation || 0,
			estimatedDirectLossUsd: targetC.estimatedDirectEconomicLossUsd || 0,
			aggregateLossPercentage: targetC.aggregateLossRatioPercentage || 0,
			damagedCriticalFacilities: targetD.totalDamagedFacilities || 0,
		},
		topDamagedAssets: (params.topDamagedAssets || []).slice(0, 10).map((a) => ({
			name: a.name,
			category: a.category,
			meanDamageRatio: a.meanDamageRatio,
			estimatedLossUsd: a.estimatedEconomicLossUsd,
		})),
	};

	if (options.mock) {
		return {
			success: true,
			recordId: `draft_rec_${Date.now()}`,
			action: "created_mock_draft",
			record: draftRecord,
		};
	}

	const result = await callDeltaMcp("disaster-record_add", {
		records: [draftRecord],
	});

	return {
		success: true,
		result,
		record: draftRecord,
	};
}

/**
 * Fetch baseline administrative divisions or historical records from DELTA
 * @param {string} entity - "division" or "disaster-record"
 * @param {object} filter - Query parameters
 * @param {object} options - Optional mock flag
 */
async function fetchExposureFromDelta(entity = "division", filter = {}, options = {}) {
	if (options.mock) {
		return {
			entity,
			page: 1,
			items: [
				{ id: "div_1", name: "Capital District", countryAccountsId: "demo_country" },
				{ id: "div_2", name: "Coastal Province", countryAccountsId: "demo_country" },
			],
		};
	}

	const toolName = `${entity}_list`;
	return callDeltaMcp(toolName, filter);
}

module.exports = {
	callDeltaMcp,
	pushDraftDisasterRecord,
	fetchExposureFromDelta,
};
